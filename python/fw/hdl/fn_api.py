# The XLS binding
# ----------------------------------------------------------------------

@dc.dataclass
class FnModule:
    """What the binding needs from XLS's ModuleSignatureProto of a function."""
    module: str
    inputs: List[tuple]          # (port, width), in order
    output: tuple                # (port, width)
    clock: str
    reset: Optional[str]
    reset_active_low: bool
    latency: int
    input_valid: Optional[str]
    output_valid: Optional[str]


def fn_module_from_signature(text: str) -> FnModule:
    from zuspec.be.xls.signature import parse_textproto, _one
    sig = parse_textproto(text)
    ins, outs = [], []
    for p in sig.get("data_ports", []):
        port = (_one(p, "name"), int(_one(p, "width")))
        (ins if _one(p, "direction") == "PORT_DIRECTION_INPUT" else outs).append(port)
    if len(outs) != 1:
        raise ValueError(f"{_one(sig, 'module_name')}: a function module has one output, "
                         f"found {len(outs)} (is it a proc?)")
    pipe = _one(sig, "pipeline", {}) or {}
    ctl = _one(pipe, "pipeline_control", {}) or {}
    valid = _one(ctl, "valid", {}) or {}
    reset = _one(sig, "reset", {}) or {}
    return FnModule(
        module=_one(sig, "module_name"), inputs=ins, output=outs[0],
        clock=_one(sig, "clock_name") or "clk",
        reset=_one(reset, "name") if reset else None,
        reset_active_low=bool(_one(reset, "active_low", False)) if reset else False,
        latency=int(_one(pipe, "latency", 0) or 0),
        input_valid=_one(valid, "input_name") if valid else None,
        output_valid=_one(valid, "output_name") if valid else None)


_DIM = re.compile(r"\[(-?\d+):(-?\d+)\]")


def _dims(a: ApiArg):
    """[(first index, step, length)] of an unpacked argument, outermost first."""
    out = []
    for left, right in _DIM.findall(a.dims):
        left, right = int(left), int(right)
        out.append((left, 1 if right >= left else -1, abs(right - left) + 1))
    return out


def _loops(a: ApiArg, body: str) -> List[str]:
    """Nested loops over every element of unpacked *a*. *body* uses `{idx}`
    (the SV index, e.g. `[k0][k1]`) and `{off}` (the element's bit offset).

    XLS flattens an array with element 0 in the low bits, and each element
    the same way in turn: element (k0, k1, ...) of an array whose element is
    W bits sits at ((k0 * n1 + k1) * n2 + ...) * W."""
    dims = _dims(a)
    idx = "".join(
        f"[{(f'{l} + k{i}' if l else f'k{i}') if st > 0 else f'{l} - k{i}'}]"
        for i, (l, st, _) in enumerate(dims))
    flat = "k0"
    for i, (_, _, n) in enumerate(dims[1:], start=1):
        flat = f"({flat}) * {n} + k{i}"
    off = f"({flat}) * {a.bits}"
    out, pad = [], "        "
    for i, (_, _, n) in enumerate(dims):
        out.append(f"{pad}for (int k{i} = 0; k{i} < {n}; k{i}++)")
        pad += "    "
    out.append(pad + body.format(idx=idx, off=off))
    return out


def _pack(a: ApiArg, port: str) -> List[str]:
    """Statements that put argument *a* on its port's queue."""
    if not a.dims:
        return [f"        q_{port}.push_back({a.name});"]
    return _loops(a, f"p_{port}[{{off}} +: {a.bits}] = {a.name}{{idx}};") + \
        [f"        q_{port}.push_back(p_{port});"]


def xls_binding_sv(api: FnApi, mods: Dict[str, FnModule], period: int = 10,
                   reset_cycles: int = 4, timeout_cycles: int = 100000) -> str:
    n = api.name
    o = [_HEADER.format(task="fw.hdl.api.XlsBinding", src=f"{n} and the XLS signatures"),
         "// Level `rtl` (and `gates`): the API is answered by the XLS modules, through",
         "// a transactor on each module's pins. Latency and port names come from",
         "// the XLS signatures, so a change of pipeline depth changes nothing here",
         "// by hand.", ""]
    for f in api.functions:
        m = mods[f.module]
        if m.input_valid is None or m.output_valid is None:
            raise ValueError(f"{m.module}: generated without valid signals; set Codegen's "
                             f"input_valid_signal and output_valid_signal")
        if len(m.inputs) != len(f.args):
            raise ValueError(f"{m.module}: {len(m.inputs)} input ports for {len(f.args)} "
                             f"arguments of {f.path}")
        rw = m.output[1]
        o += [f"// {f.path} -> module {m.module}, latency {m.latency}",
              f"interface {m.module}_xtor_if (input bit clk, input bit rst);"]
        o += [f"    bit [{w - 1}:0] {port};" for port, w in m.inputs]
        o += [f"    bit {m.input_valid};",
              f"    bit [{rw - 1}:0] {m.output[0]};",
              f"    bit {m.output_valid};", ""]
        o += [f"    bit [{w - 1}:0] q_{port}[$];   // calls not yet presented"
              for port, w in m.inputs]
        o += [f"    bit [{rw - 1}:0] results[int unsigned];   // by call number",
              "    int unsigned issued, collected;", "",
              "    // Present one queued call per cycle; collect results in order.",
              "    always @(posedge clk) begin",
              "        if (rst) begin",
              f"            {m.input_valid} <= 1'b0;",
              "        end else begin"]
        first = m.inputs[0][0] if m.inputs else None
        if first:
            o += [f"            if (q_{first}.size() != 0) begin",
                  f"                {m.input_valid} <= 1'b1;"]
            o += [f"                {port} <= q_{port}.pop_front();" for port, _ in m.inputs]
            o += ["            end else begin",
                  f"                {m.input_valid} <= 1'b0;",
                  "            end"]
        o += [f"            if ({m.output_valid}) begin",
              f"                results[collected] = {m.output[0]};",
              "                collected++;",
              "            end",
              "        end",
              "    end", ""]
        sig_args = [f"input {a.decl()}" for a in f.args] + [f"output {f.ret.decl()}"]
        o += [f"    task automatic call({', '.join(sig_args)});",
              "        int unsigned t = issued++;"]
        o += [f"        bit [{w - 1}:0] p_{port};" for a, (port, w) in zip(f.args, m.inputs)
              if a.dims]
        if f.ret.dims:
            o.append(f"        bit [{rw - 1}:0] r;")
        for a, (port, _) in zip(f.args, m.inputs):
            o += _pack(a, port)
        o.append("        while (!results.exists(t)) @(posedge clk);")
        if f.ret.dims:
            o.append("        r = results[t];")
            o += _loops(f.ret, f"result{{idx}} = r[{{off}} +: {f.ret.bits}];")
        else:
            o.append("        result = results[t];")
        o += ["        results.delete(t);",
              "    endtask",
              "endinterface", ""]

    o += [f"package {n}_xls_pkg;",
          f"    // The bridge: the API, answered by the transactor interfaces.",
          f"    class {n}_xls implements {api.pkg}::{n};"]
    o += [f"        virtual {mods[f.module].module}_xtor_if {f.name}_if;" for f in api.functions]
    for f in api.functions:
        o += [f"        virtual {_task_sig(f)};",
              f"            {f.name}_if.call({_call_args(f)});",
              "        endtask"]
    o += ["    endclass", "endpackage", ""]

    o += [f"module {n}_harness;",
          "    bit clk = 1'b0;",
          "    bit rst = 1'b1;",
          f"    always #{period // 2} clk = ~clk;",
          "    initial begin",
          f"        repeat ({reset_cycles}) @(posedge clk);",
          "        rst <= 1'b0;",
          "    end", ""]
    if timeout_cycles:
        o += ["    // A call that never completes fails the run instead of stalling it.",
              "    initial begin",
              f"        repeat ({timeout_cycles}) @(posedge clk);",
              f"        $fatal(1, \"{n}_harness: timeout after {timeout_cycles} cycles\");",
              "    end", ""]
    for f in api.functions:
        m = mods[f.module]
        o.append(f"    {m.module}_xtor_if {f.name}_if (.clk(clk), .rst(rst));")
        conns = [f".{m.clock}(clk)"]
        if m.reset:
            conns.append(f".{m.reset}({'!rst' if m.reset_active_low else 'rst'})")
        conns += [f".{p}({f.name}_if.{p})" for p, _ in m.inputs]
        conns += [f".{m.input_valid}({f.name}_if.{m.input_valid})",
                  f".{m.output[0]}({f.name}_if.{m.output[0]})",
                  f".{m.output_valid}({f.name}_if.{m.output_valid})"]
        o += [f"    {m.module} u_{f.name} (", "        " + ",\n        ".join(conns), "    );", ""]
    o += ["    initial begin",
          f"        automatic {n}_xls_pkg::{n}_xls x = new();"]
    o += [f"        x.{f.name}_if = {f.name}_if;" for f in api.functions]
    o += [f"        {api.pkg}::bind_api(x);",
          "    end",
          "endmodule", ""]
    return "\n".join(o)
