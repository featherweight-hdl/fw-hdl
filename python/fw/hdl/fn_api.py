"""The call API of SV functions (xls-examples.md G-9, TB-2).

A test calls a design through an API: an interface class with one task per
exported function. The test holds the API, never a binding, so the same test
runs at every level:

    <api>_pkg.sv     (Functions)     interface class <api>, the proxy a test
                                     gets from <api>_pkg::get(), and <api>_model,
                                     which calls the SV function
    <api>_model.sv   (ModelBinding)  module <api>_harness: binds <api>_model
    <api>_xls.sv     (XlsBinding)    per function, a transactor interface on the
                                     XLS module's pins; the bridge class; module
                                     <api>_harness: clock, reset, the modules,
                                     and the bridge bound as the API

Each level supplies a module named `<api>_harness`, so the test bench that
instantiates it never changes. The binding is registered at time 0; the proxy
waits one time step for it on a first call.

A task, not a function, because a call takes time when RTL answers it.
"""
from __future__ import annotations

import dataclasses as dc
import json
import re
from typing import Dict, List, Optional, Sequence

from pyslang import ast

API_FORMAT = "fw.hdl.fn-api"
API_VERSION = 1


@dc.dataclass
class ApiArg:
    name: str
    #: SV type, as declared (package-qualified): `bit[7:0]`, `crc32_pkg::digest_t`.
    type: str
    #: Unpacked dimensions, as a declarator suffix (`[0:7]`); empty for none.
    dims: str = ""
    bits: int = 0
    signed: bool = False

    def decl(self, name: Optional[str] = None) -> str:
        return f"{self.type} {name or self.name}{self.dims}"


@dc.dataclass
class ApiFn:
    name: str            # the SV function's name: the API task's name
    path: str            # its hierarchical path: crc32_pkg::main
    module: str          # the module XLS makes of it: crc32_pkg__main
    args: List[ApiArg]
    ret: ApiArg          # name "result"


@dc.dataclass
class FnApi:
    name: str            # crc32_pkg_api
    functions: List[ApiFn]
    sources: List[str] = dc.field(default_factory=list)

    @property
    def pkg(self) -> str:
        return f"{self.name}_pkg"

    def save(self, path: str):
        with open(path, "w") as f:
            json.dump({"format": API_FORMAT, "version": API_VERSION, **dc.asdict(self)},
                      f, indent=2)

    @staticmethod
    def load(path: str) -> "FnApi":
        with open(path) as f:
            d = json.load(f)
        if d.get("format") != API_FORMAT:
            raise ValueError(f"{path}: not a {API_FORMAT} file")
        fns = [ApiFn(f["name"], f["path"], f["module"], [ApiArg(**a) for a in f["args"]],
                     ApiArg(**f["ret"])) for f in d["functions"]]
        return FnApi(d["name"], fns, d.get("sources", []))


# ----------------------------------------------------------------------
# From the SV
# ----------------------------------------------------------------------

def _arg(name: str, t) -> ApiArg:
    dims = ""
    while t.isUnpackedArray:
        ct = t.canonicalType
        if ct.kind != ast.SymbolKind.FixedSizeUnpackedArrayType:
            raise ValueError(f"{name}: only fixed-size unpacked arrays can cross the API")
        dims += f"[{ct.range.left}:{ct.range.right}]"
        t = ct.elementType
    return ApiArg(name=name, type=str(t), dims=dims, bits=int(t.bitWidth),
                  signed=bool(t.isSigned))


def api_from_subroutines(name: str, subs, module_of) -> FnApi:
    fns = []
    for s in subs:
        args = [_arg(a.name, a.type) for a in s.arguments]
        fns.append(ApiFn(name=s.name, path=s.hierarchicalPath, module=module_of(s),
                         args=args, ret=_arg("result", s.returnType)))
    names = [f.name for f in fns]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise ValueError(f"API {name}: two functions named {dup}; an API task "
                         f"needs a unique name")
    return FnApi(name=name, functions=fns)


def default_api_name(paths: Sequence[str]) -> str:
    """`crc32_pkg::main` -> `crc32_pkg_api`: the first function's scope."""
    scope = paths[0].rsplit("::", 1)[0] if "::" in paths[0] else paths[0]
    return re.sub(r"\W", "_", scope.replace("::", "__")) + "_api"


# ----------------------------------------------------------------------
# SV text
# ----------------------------------------------------------------------

def _task_sig(f: ApiFn) -> str:
    args = [f"input {a.decl()}" for a in f.args] + [f"output {f.ret.decl()}"]
    return f"task {f.name}({', '.join(args)})"


def _call_args(f: ApiFn) -> str:
    return ", ".join([a.name for a in f.args] + ["result"])


_HEADER = "// Generated by {task} from {src}. Do not edit.\n"


def api_pkg_sv(api: FnApi) -> str:
    n = api.name
    fns = api.functions
    o = [_HEADER.format(task="fw.hdl.api.Functions", src=", ".join(api.sources) or "SV"),
         f"package {api.pkg};", "",
         f"    // The call API: one task per function. A test holds an {n}",
         "    // and does not know which level answers it.",
         f"    interface class {n};"]
    o += [f"        pure virtual {_task_sig(f)};" for f in fns]
    o += ["    endclass", "",
          "    // What get() returns: forwards each call to the binding the level",
          "    // registered with bind_api().",
          f"    class {n}_proxy implements {n};",
          f"        static {n} impl;", ""]
    for f in fns:
        o += [f"        virtual {_task_sig(f)};",
              "            if (impl == null) #1;   // the binding registers at time 0",
              "            if (impl == null)",
              f"                $fatal(1, \"{n}: no binding; the test bench needs a {n}_harness\");",
              f"            impl.{f.name}({_call_args(f)});",
              "        endtask"]
    o += ["    endclass", "",
          f"    function automatic {n} get();",
          f"        {n}_proxy p = new();",
          "        return p;",
          "    endfunction", "",
          f"    function automatic void bind_api({n} impl);",
          f"        {n}_proxy::impl = impl;",
          "    endfunction", "",
          "    // The model binding: each call runs the SV function itself.",
          f"    class {n}_model implements {n};"]
    for f in fns:
        o += [f"        virtual {_task_sig(f)};",
              f"            result = {f.path}({', '.join(a.name for a in f.args)});",
              "        endtask"]
    o += ["    endclass", "", "endpackage", ""]
    return "\n".join(o)


def model_harness_sv(api: FnApi) -> str:
    n = api.name
    return "\n".join([
        _HEADER.format(task="fw.hdl.api.ModelBinding", src=f"{n}"),
        f"// Level `model`: the API is answered by the SV functions.",
        f"module {n}_harness;",
        "    initial begin",
        f"        automatic {api.pkg}::{n}_model m = new();",
        f"        {api.pkg}::bind_api(m);",
        "    end",
        "endmodule", ""])


