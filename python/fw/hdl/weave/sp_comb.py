"""The fw_sp_comb weaver (plan S6.1b): comb fields declared on a port member,
``(* fw_sp_comb = "ar.*,w.valid" *) axi4_sub_sp #(P) s;``, become the
``set_comb`` calls that fix them at the end of build (design-sync-rtl §2
"Declaration").

For every class (specialization) that declares such a member, ``<pkg>_woven``
gets a subclass of ``fw_hdl_pkg::fw_sp_comb`` whose ``apply(c)`` ``$cast``\\s c to
the class and calls, per member, ``m.holder().set_comb(..)`` (a one-channel view,
``fw_sync_port``; items are ``f``, ``*`` or ``<member>.f``) or ``m.set_comb(..)``
(a port of channels with its own ``set_comb``, e.g. fw_proto ``fw_sp_base``; items
are ``ch.f`` or ``ch.*``). Its registration adds it to ``fw_sp_comb::m_all``;
``fw_sync_kernel::freeze_tree`` applies them to the tree. A subclass instance
matches its base's ``$cast`` too, so it inherits the declarations.

Checked here: the member is a public struct port, the list is not empty, and a
channel prefix names one of the port's channels (its ``fw_sig_holder`` members)
or, for a view, the member itself. Field names are checked at run time
(``check_comb``, fatal), and so are channel names when the port class is not in
the model (a class generated by another weave run)."""
import re
from typing import List, Optional

from sv_weave.frontend.model import Visibility
from sv_weave.plugin import Weaver

from .settle import SettleWeaver

ATTR = "fw_sp_comb"
HOLDER = "fw_sig_holder"
VIEW = "fw_sync_port"


def _q(s: str) -> str:
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def _base(spelling: str) -> str:
    return (spelling or "").split("#")[0].split("::")[-1].strip()


class SpCombWeaver(Weaver):
    name = "fw_sp_comb"
    version = "0.1"

    def subscribe(self, bus):
        bus.on_design(self.design)

    def design(self, d):
        by_name = {}
        for k in d.model.classes():
            by_name.setdefault(k.generic.name if k.generic else k.name, k)
        n = {}
        for c in sorted(d.model.classes(), key=lambda c: c.qname):
            if c.is_interface or c.package is None:
                continue
            calls = []
            for f in c.fields:
                if ATTR not in f.attrs:
                    continue
                call = self._call(d, c, f, by_name)
                if call is not None:
                    calls.append(call)
            if not calls:
                continue
            ty = SettleWeaver._type(c)
            if ty is None:
                d.error("fw_sp_comb: %s has a type argument the woven package cannot name"
                        % c.qname, c.loc)
                continue
            i = n.get(c.package, 0)
            n[c.package] = i + 1
            cls = "fw_sp_comb__%s_%d" % (re.sub(r"\W", "_", c.name), i)
            d.add_item(c.package, "\n".join(
                ["// %s" % c.qname,
                 "class %s extends fw_hdl_pkg::fw_sp_comb;" % cls,
                 "    virtual function bit apply(fw_hdl_pkg::fw_component c);",
                 "        %s t;" % ty,
                 "        if (!$cast(t, c)) return 0;"]
                + ["        %s;" % s for s in calls]
                + ["        return 1;", "    endfunction", "endclass"]))
            d.add_registration(c.package, "begin\n  %s a = new();\n"
                               "  fw_hdl_pkg::fw_sp_comb::add(a);\nend" % cls)

    def _call(self, d, c, f, by_name) -> Optional[str]:
        where = "fw_sp_comb: %s.%s" % (c.qname, f.name)
        spec = str(f.attrs[ATTR]).strip().strip('"')
        items: List[str] = [s.strip() for s in spec.split(",") if s.strip()]
        if not items:
            d.error("%s: empty field list" % where, f.loc)
            return None
        if f.visibility != Visibility.PUBLIC or f.static:
            d.error("%s: the member must be public and not static" % where, f.loc)
            return None
        pc = by_name.get(_base(f.type.spelling))
        if pc is not None and pc.is_a(VIEW):
            out = []
            for it in items:
                ch, dot, fld = it.rpartition(".")
                if dot and ch != f.name:
                    d.error('%s: "%s": a one-channel port takes "f", "*" or "%s.f"'
                            % (where, it, f.name), f.loc)
                    return None
                out.append(fld)
            return "t.%s.holder().set_comb(%s)" % (f.name, _q(",".join(out)))
        # A class the model does not hold (e.g. generated in another weave run):
        # assume a port of channels; its set_comb checks the names at run time.
        if (pc is not None and pc.find_method("set_comb") is not None) or \
                (pc is None and f.type.class_qname):
            chans = set() if pc is None else {g.name for g in pc.all_fields()
                     if g.name and (by_name.get(_base(g.type.spelling)) is not None
                                    and by_name[_base(g.type.spelling)].is_a(HOLDER))}
            for it in items:
                ch, dot, _ = it.partition(".")
                if not dot or (chans and ch not in chans):
                    d.error('%s: "%s": no channel "%s" in %s (write ch.f or ch.*; '
                            "channels: %s)" % (where, it, ch if dot else "",
                                               f.type.spelling if pc is None else pc.qname,
                                               ", ".join(sorted(chans)) or "none"), f.loc)
                    return None
            return "t.%s.set_comb(%s)" % (f.name, _q(",".join(items)))
        d.error("%s: %s is not a struct port (an %s view, or a port with set_comb)"
                % (where, f.type.spelling, VIEW), f.loc)
        return None
