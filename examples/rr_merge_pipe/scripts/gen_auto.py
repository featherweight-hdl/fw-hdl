"""F6, the thin automated slice: rr_merge_pipe (v0) with its input map
recognized and pipelined by the spike (python/fw/hdl/spikes), Zuspec IR to
Zuspec IR, then emitted by zuspec-be-sv unchanged:

    rtl/gen/rr_merge_pipe_auto<K>.sv   module rr_merge_pipe_auto<K>

Also prints the new component as a crude sync class (a probe of projecting
IR back to source, not a deliverable). Run from examples/rr_merge_pipe:

    direnv exec . env PYTHONPATH=$PWD/../../python python scripts/gen_auto.py [K ...]
"""
import os
import sys

import zuspec.ir.core as ir

from fw.hdl.emit.be_sv import emit_sv
from fw.hdl.emit.sync import elab_sync_param
from fw.hdl.spikes.dataflow import MapMatch, match_map
from fw.hdl.spikes.pipeline import pipeline_design, project_class

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_rtl import FILES, HERE, INCDIRS  # noqa: E402


def main(*ks: str) -> int:
    irs = elab_sync_param(FILES, "rr_merge_pipe_emit_top", incdirs=INCDIRS,
                          vars=["rr_merge_pipe"])["rr_merge_pipe"]
    m = match_map(irs["pipe_map_in"])
    if not isinstance(m, MapMatch):
        print(f"pipe_map_in is not a map: {m.reason}")
        return 1
    for k in [int(x) for x in ks] or [1, 2]:
        name = f"rr_merge_pipe_auto{k}"
        out = pipeline_design(irs, "rr_merge_pipe", "min", m, k, name)
        path = f"{HERE}/rtl/gen/{name}.sv"
        with open(path, "w") as f:
            f.write("// Generated by scripts/gen_auto.py (spike F6). Do not edit.\n")
            f.write(emit_sv(ir.Context(type_m=out)))
        print(f"wrote {path}")
        proj = f"{HERE}/rundir/{name}_projection.svh"
        os.makedirs(os.path.dirname(proj), exist_ok=True)
        with open(proj, "w") as f:
            f.write(project_class(out[f"pipe_map_in_stall{k}"], out))
        print(f"wrote {proj}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
