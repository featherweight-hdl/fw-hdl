"""Lower the rr_merge_pipe classes to Verilog: rtl/gen/<var>.sv.

Runs the fw-hdl sync flow (static elaboration -> Zuspec IR -> zuspec-be-sv,
parameterized: one module per class) on the class variables of
rtl/rr_merge_pipe_emit_top.sv. Run from examples/rr_merge_pipe:

    direnv exec . env PYTHONPATH=$PWD/../../python python scripts/gen_rtl.py [var ...]
"""
import os
import sys

from fw.hdl.emit.sync import emit_sync

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(HERE))
MERGE = f"{ROOT}/examples/rr_merge/src"
FILES = [f"{ROOT}/src/fw_clock_xtor_if.sv", f"{ROOT}/src/fw_clock_period_xtor_if.sv",
         f"{ROOT}/src/fw_hdl_pkg.sv",
         f"{HERE}/src/pipe_types_pkg.sv", f"{HERE}/src/rr_merge_pipe_pkg.sv",
         f"{HERE}/rtl/rr_merge_pipe_emit_top.sv"]
INCDIRS = [f"{ROOT}/src", MERGE, f"{HERE}/src"]


def main(*names: str) -> int:
    out_dir = f"{HERE}/rtl/gen"
    os.makedirs(out_dir, exist_ok=True)
    out = emit_sync(FILES, "rr_merge_pipe_emit_top", incdirs=INCDIRS,
                    vars=list(names) or None, parameterized=True)
    for var, text in out.items():
        path = f"{out_dir}/{var}.sv"
        with open(path, "w") as f:
            f.write("// Generated by scripts/gen_rtl.py from src/*.svh. Do not edit.\n")
            f.write(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
