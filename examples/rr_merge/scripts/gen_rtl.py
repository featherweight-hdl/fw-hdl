"""Lower the rr_merge classes to Verilog: rtl/gen/rr_merge.sv.

Runs the fw-hdl sync flow (static elaboration -> Zuspec IR -> zuspec-be-sv)
on the class variables of rtl/rr_merge_emit_top.sv. The composite `rr_merge`
is written with the modules of its children, one parameterized module per
class (`rr_arbiter #(T, N)`, `rr_fifo #(T, DEPTH)`), and the package
`rr_merge_types` with the default beat type. Stand-in for the dfm task
fw.hdl.sync.Emit until the fw-hdl Python package is installed in the env:

    direnv exec . env PYTHONPATH=$PWD/../../python python scripts/gen_rtl.py
"""
import os
import sys

from fw.hdl.emit.sync import emit_sync

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(HERE))
FILES = [f"{ROOT}/src/fw_clock_xtor_if.sv", f"{ROOT}/src/fw_clock_period_xtor_if.sv",
         f"{ROOT}/src/fw_hdl_pkg.sv", f"{HERE}/src/rr_merge_pkg.sv",
         f"{HERE}/rtl/rr_merge_emit_top.sv"]


def main(out_dir: str = f"{HERE}/rtl/gen") -> int:
    os.makedirs(out_dir, exist_ok=True)
    out = emit_sync(FILES, "rr_merge_emit_top", incdirs=[f"{ROOT}/src", f"{HERE}/src"],
                    vars=["rr_merge"], parameterized=True)
    path = f"{out_dir}/rr_merge.sv"
    with open(path, "w") as f:
        f.write("// Generated by scripts/gen_rtl.py from src/*.svh. Do not edit.\n")
        f.write(out["rr_merge"])
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
