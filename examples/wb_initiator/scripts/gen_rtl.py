"""Lower the Wishbone initiator's sync core to Verilog: rtl/gen/wb_init_core.sv.

Runs the fw-hdl sync flow (static elaboration -> Zuspec IR -> zuspec-be-sv)
on the class variable of rtl/wb_init_emit_top.sv. Run from
examples/wb_initiator:

    direnv exec . env PYTHONPATH=$PWD/../../python python scripts/gen_rtl.py
"""
import os
import sys

from fw.hdl.emit.sync import emit_sync

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(HERE))
FILES = [f"{ROOT}/src/fw_clock_xtor_if.sv", f"{ROOT}/src/fw_clock_period_xtor_if.sv",
         f"{ROOT}/src/fw_hdl_pkg.sv",
         f"{HERE}/ref/wb_types_pkg.sv", f"{HERE}/src/wb_init_core_pkg.sv",
         f"{HERE}/rtl/wb_init_emit_top.sv"]
INCDIRS = [f"{ROOT}/src", f"{HERE}/src"]
# The emit top's variables, by the file they are written to.
FILE = {"core": "wb_init_core"}


def main(*names: str) -> int:
    out_dir = f"{HERE}/rtl/gen"
    os.makedirs(out_dir, exist_ok=True)
    out = emit_sync(FILES, "wb_init_emit_top", incdirs=INCDIRS,
                    vars=list(names) or None, parameterized=True)
    for var, text in out.items():
        path = f"{out_dir}/{FILE.get(var, var)}.sv"
        with open(path, "w") as f:
            f.write("// Generated by scripts/gen_rtl.py from src/wb_init_core.svh. Do not edit.\n")
            f.write(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
